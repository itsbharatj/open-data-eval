"""Benchmark the metric landscape (no Habitat needed).

1. Reproduces the published CMA baseline Scores from their component metrics.
2. Tabulates Score over an (SR, NE, TCR) grid to show what wins.
3. Reports the Score sensitivity (finite differences) at plausible operating points.
Writes benchmarks/score_landscape.md.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from havln_tools import composite_score  # noqa: E402

CMA = {
    "val_seen": dict(SR=0.180, NE=6.223, CR=0.623, TCR=13.726, Score=16.509450),
    "val_unseen": dict(SR=0.129, NE=6.387, CR=0.684, TCR=17.536, Score=12.945387),
}


def main() -> None:
    out = ["# Score landscape benchmark", "", "Generated by `python benchmarks/score_landscape.py`.", ""]
    out += ["## 1. Baseline reproduction (README components -> Score)", "", "| split | published | recomputed | diff |", "|---|---|---|---|"]
    for split, m in CMA.items():
        got = composite_score(m["SR"], m["NE"], m["CR"], m["TCR"])
        out.append(f"| {split} | {m['Score']:.6f} | {got:.6f} | {got - m['Score']:+.4f} |")
    out += ["", "Residual < 0.01 comes from the 3-decimal rounding of the displayed components.", ""]

    out += ["## 2. Score grid (CR derived as min(TCR,1) share; zero-collision rows have CR=0)", "",
            "| SR | NE (m) | TCR | CR | Score |", "|---|---|---|---|---|"]
    for sr in (0.13, 0.3, 0.5, 0.7, 0.8, 0.9, 0.95, 1.0):
        for ne in (1.0, 2.0, 4.0, 6.5):
            for tcr, cr in ((0.0, 0.0), (0.1, 0.1), (1.0, 0.5), (15.0, 0.65)):
                out.append(f"| {sr:.2f} | {ne:.1f} | {tcr:.1f} | {cr:.2f} | {composite_score(sr, ne, cr, tcr):.2f} |")
    out.append("")

    out += ["## 3. Sensitivity at operating points (dScore per unit)", "", "| point | dScore/dSR (+0.01) | dScore/dNE (+0.1 m) | dScore/dTCR (+0.01, CR +0.01) |", "|---|---|---|---|"]
    for sr, ne, cr, tcr in ((0.5, 2.0, 0.0, 0.0), (0.8, 1.5, 0.0, 0.0), (0.9, 1.0, 0.0, 0.0), (0.6, 3.0, 0.2, 0.3)):
        base = composite_score(sr, ne, cr, tcr)
        d_sr = composite_score(sr + 0.01, ne, cr, tcr) - base
        d_ne = composite_score(sr, ne + 0.1, cr, tcr) - base
        d_c = composite_score(sr, ne, cr + 0.01, tcr + 0.01) - base
        out.append(f"| SR={sr} NE={ne} CR={cr} TCR={tcr} (Score {base:.2f}) | {d_sr:+.3f} | {d_ne:+.3f} | {d_c:+.3f} |")
    out += ["", "Reading: one percentage point of SR is worth about 0.8 Score; 0.1 m of mean NE is worth about 0.2 Score "
            "at NE~1-2 m; each 0.01 of collision rate costs about 0.2 Score. Collision-free execution is a 30% multiplier.", ""]

    out += ["## 4. Headline comparisons", ""]
    rows = [("CMA baseline (val_unseen)", composite_score(0.129, 6.387, 0.684, 17.536)),
            ("Strong closed-loop agent, SR .55 NE 3.0, few collisions (CR .15, TCR .2)", composite_score(0.55, 3.0, 0.15, 0.2)),
            ("Offline map planner, goal top-1 .70, NE 2.0, zero collisions", composite_score(0.70, 2.0, 0.0, 0.0)),
            ("Offline map planner, goal top-1 .85, NE 1.3, zero collisions", composite_score(0.85, 1.3, 0.0, 0.0)),
            ("Oracle goals, zero collisions, NE .5", composite_score(0.98, 0.5, 0.0, 0.0))]
    out += ["| scenario | Score |", "|---|---|"] + [f"| {n} | {s:.2f} |" for n, s in rows] + [""]
    text = "\n".join(out)
    (Path(__file__).resolve().parent / "score_landscape.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
